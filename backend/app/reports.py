"""Deterministic final report. Built from stored facts (never written by a model), so it cannot overstate success."""
from __future__ import annotations

from collections import Counter

from .store import Store


def build_report(store: Store, tid: str) -> dict:
    t = store.get_task(tid)
    subs = store.subtasks(tid)
    reviews = store.reviews(tid)
    tests = store.test_runs(tid)
    claims = store.claims(tid)
    sources = store.sources(tid)
    proposals = store.proposals(tid)
    usage = store.task_usage(tid)

    done = [s for s in subs if s["status"] == "done"]
    problems = [s for s in subs if s["status"] in ("failed", "skipped")]
    pending = [p for p in proposals if p["status"] in ("pending", "approved")]

    failed_checks: list[str] = []
    last_test = tests[-1] if tests else None
    if last_test and last_test["status"] in ("failed", "error", "timeout"):
        failed_checks.append(f"Automated tests {last_test['status']} ({last_test['command']})")
    if reviews and reviews[-1]["verdict"] == "fail" or (reviews and any(i["severity"] == "blocker" for i in reviews[-1]["issues"])):
        failed_checks.append("Independent review still reports blocking issues")
    unresolved = [f"{i['severity']}: {i['description']}" for i in (reviews[-1]["issues"] if reviews else []) if t["unresolved_issues"]]

    deliverables = []
    for s in done:
        o = s["output"]
        entry = {"subtask": s["title"], "kind": s["kind"], "agent": s["agent"]}
        if s["kind"] in ("synthesis", "document"):
            entry.update(title=o.get("title"), content=o.get("content"), open_issues=o.get("open_issues", []))
        elif s["kind"] == "analysis":
            entry.update(summary=o.get("summary"), content=o.get("content"), recommendation=o.get("recommendation"),
                         uncertainties=o.get("uncertainties") or o.get("risks"))
        elif s["kind"] == "research":
            entry.update(summary=o.get("summary"), cached=o.get("cached"), no_web_access=o.get("no_web_access"),
                         limitations=o.get("limitations"), unresolved_questions=o.get("unresolved_questions"))
        elif s["kind"] == "implementation":
            entry.update(summary=o.get("summary"), files=o.get("files"), proposal_id=o.get("proposal_id"))
        deliverables.append(entry)

    by_agent: dict[str, dict] = {}
    for s in subs:
        a = by_agent.setdefault(s["agent"], {"subtasks": [], "calls": 0})
        a["subtasks"].append(f"{s['title']} ({s['status']})")
    for row in usage["by_provider"]:
        by_agent.setdefault(row["provider"], {"subtasks": [], "calls": 0})["calls"] = row["calls"]
    for r in reviews:
        by_agent.setdefault(r["reviewer"], {"subtasks": [], "calls": 0})["subtasks"].append(f"review round {r['round']} ({r['verdict']})")

    if t["status"] == "completed":
        headline = "Completed with unresolved issues" if t["outcome"] == "completed_with_issues" else "Completed"
    elif t["status"] == "awaiting_approval":
        headline = "Awaiting your approval" + (" (unresolved issues flagged)" if t["unresolved_issues"] else "")
    elif t["status"] == "failed":
        headline = "Partially completed: some work failed" if t["outcome"] == "partial" else "Failed"
    else:
        headline = t["status"].replace("_", " ").capitalize()

    cost_line = ("Demo mode: no billable calls were made." if usage["demo"] else
                 f"{usage['billable_calls']} billable call(s), about ${usage['cost_usd']:.4f} (provider-reported where available, otherwise estimated from tokens).")

    caveats: list[str] = []
    if any(s["kind"] == "research" and s["output"].get("no_web_access") for s in done):
        caveats.append("Research ran WITHOUT live web access (Perplexity unavailable or not selected): findings come from model knowledge and are unverified.")
    open_claims = sum(1 for c in claims if c["status"] != "verified")
    if claims and open_claims:
        caveats.append(f"{open_claims} of {len(claims)} research claim(s) are not verified (unverified, conflicting or outdated).")
    if usage["demo"]:
        caveats.append("Demo mode: outputs were generated by offline mock providers, not real AI models or web search.")

    return {
        "headline": headline,
        "caveats": caveats,
        "outcome": t["outcome"],
        "completed_subtasks": [s["title"] for s in done],
        "problem_subtasks": [{"title": s["title"], "status": s["status"], "error": s["error"]} for s in problems],
        "deliverables": deliverables,
        "failed_checks": failed_checks,
        "unresolved_issues": unresolved,
        "required_approvals": [{"proposal_id": p["id"], "version": p["version"], "files": [f["path"] for f in p["files"]]} for p in pending],
        "agents": by_agent,
        "claims": dict(Counter(c["status"] for c in claims)),
        "source_count": len(sources),
        "reviews": [{"reviewer": r["reviewer"], "round": r["round"], "verdict": r["verdict"], "issues": len(r["issues"])} for r in reviews],
        "tests": [{"status": x["status"], "command": x["command"]} for x in tests],
        "usage": usage,
        "cost_statement": cost_line,
    }
